function dump_smoke_matrices (output_path)
  % Dump the concrete small smoke fixtures produced by the existing
  % NEIGT/SVT generators in an exact dyadic interchange format.
  %
  % This is a documentation QA helper, not a package API.  It deliberately
  % calls the same private example constructors used by the runnable cases.
  if (nargin != 1 || ! ischar (output_path) || isempty (output_path))
    error ("mplapack:docs:SmokeDump", "an output path is required");
  endif

  neig_private = fullfile (pwd (), "examples", "neig_tiers", "private");
  svd_private = fullfile (pwd (), "examples", "svd_tiers", "private");
  addpath (neig_private);
  addpath (svd_private);

  fid = fopen (output_path, "w");
  if (fid < 0)
    error ("mplapack:docs:SmokeDump", ...
           "could not open output path: %s", output_path);
  endif
  cleanup_file = onCleanup (@() fclose (fid));
  fprintf (fid, "# case_id\tdoc_path\trows\tcolumns\trow\tcolumn\tkind\tsign\tmantissa_hex\texponent2\n");

  mpbits (256);
  neig = jsondecode (fileread (fullfile ("docs", "codex", "neigt", ...
                                         "cases.json")));
  neig_ids = {"OO53_REAL", "OO53_PAIR", "OO128_CLOSE", ...
              "SIM_SIMPLE", "SIM_REPEAT", "SIM_JORDAN", ...
              "SIM_TWO_JORDAN", "FORSYTHE", "FORSYTHE_SCALED", ...
              "FORSYTHE_ZERO", "HAD_BIDIAG", "FRANK0", "FRANK1", ...
              "WILKINSON", "MARKOV", "PERRON_POS"};
  neig_docs = {"oo53_real", "oo53_pair", "oo128_close", ...
               "sim_simple", "sim_repeat", "sim_jordan", ...
               "sim_two_jordan", "forsythe", "forsythe_scaled", ...
               "forsythe_zero", "had_bidiag", "frank0", "frank1", ...
               "wilkinson", "markov", "perron_pos"};
  for index = 1:numel (neig_ids)
    entry = neig.profiles.smoke.cases( ...
      strcmp ({neig.profiles.smoke.cases.id}, neig_ids{index}));
    fixture = net_case_model (entry, 256);
    if (strcmp (entry.tier, "S"))
      tier_name = "neig-tier-s";
    else
      tier_name = "neig-tier-a";
    endif
    write_fixture (fid, neig_ids{index}, ...
      ["docs/examples/tiered/", tier_name, "/", ...
       neig_docs{index}, ".md"], fixture.A_model);
  endfor

  svd = svt_load_manifest ();
  svd_ids = {"S1-NRO-TWO", "S1-NRO-THREE", "S1-NRO-GRADED", ...
             "S2-JS", "S3-LAH", "S4-DD-SYM", "S4-DD-NONSYM", ...
             "A1-PASCAL-LOWER", "A1-PASCAL-SYM", "A2-VAND", ...
             "A3-BDI-RAW", "A3-BDI-MIXED", "A4-LAU-TALL", ...
             "A4-LAU-WIDE", "A5-GEO", "A5-CLOSE", "A5-REPEAT", ...
             "A5-RANK4", "A5-RANK5", "A6-NRO-COMPANION"};
  svd_docs = {"nro_two", "nro_three", "nro_graded", "jacobi_stirling", ...
              "lah", "dd_sym", "dd_nonsym", "pascal_lower", ...
              "pascal_sym", "vandermonde", "bidiag_raw", "bidiag_mixed", ...
              "lauchli_tall", "lauchli_wide", "hadamard_geometric", ...
              "hadamard_close", "hadamard_repeat", "hadamard_rank4", ...
              "hadamard_rank5", "nro_companion"};
  for index = 1:numel (svd_ids)
    entry = svd.profiles.smoke.cases( ...
      strcmp ({svd.profiles.smoke.cases.id}, svd_ids{index}));
    fixture = svt_build_case (entry, 256);
    if (strcmp (entry.tier, "S"))
      tier_name = "svd-tier-s";
    else
      tier_name = "svd-tier-a";
    endif
    write_fixture (fid, svd_ids{index}, ...
      ["docs/examples/tiered/", tier_name, "/", ...
       svd_docs{index}, ".md"], fixture.A);
  endfor

  % This is a small fixed demo-only control (9x8), so keep it in the
  % explicit-matrix audit even though it is not part of the smoke profile.
  entry = svd.profiles.demo.cases( ...
    strcmp ({svd.profiles.demo.cases.id}, "A4-LAU-COMPLEX"));
  fixture = svt_build_case (entry, 256);
  write_fixture (fid, "A4-LAU-COMPLEX", ...
    "docs/examples/tiered/svd-tier-a/lauchli_complex.md", fixture.A);
endfunction

function write_fixture (fid, case_id, doc_path, matrix)
  stored_bits = 256;
  for row = 1:rows (matrix)
    for column = 1:columns (matrix)
      value = net_dyadic_encode_scalar (matrix(row, column), stored_bits);
      if (strcmp (value.kind, "real"))
        fprintf (fid, "%s\t%s\t%d\t%d\t%d\t%d\treal\t%d\t%s\t%d\n", ...
                 case_id, doc_path, rows (matrix), columns (matrix), ...
                 row, column, value.sign, value.mantissa_hex, ...
                 value.exponent2);
      else
        fprintf (fid, "%s\t%s\t%d\t%d\t%d\t%d\tcomplex-real\t%d\t%s\t%d\n", ...
                 case_id, doc_path, rows (matrix), columns (matrix), ...
                 row, column, value.real.sign, value.real.mantissa_hex, ...
                 value.real.exponent2);
        fprintf (fid, "%s\t%s\t%d\t%d\t%d\t%d\tcomplex-imag\t%d\t%s\t%d\n", ...
                 case_id, doc_path, rows (matrix), columns (matrix), ...
                 row, column, value.imag.sign, value.imag.mantissa_hex, ...
                 value.imag.exponent2);
      endif
    endfor
  endfor
endfunction
